def _band_label(raw_score: float) -> str:
    band = get_colour_band(normalise_score(raw_score))
    return str(band["label"])


def _utc(dt: Optional[datetime]) -> Optional[datetime]:
    if dt is None:
        return None
    if dt.tzinfo is None:
        return dt.replace(tzinfo=timezone.utc)
    return dt.astimezone(timezone.utc)


async def _get_department(db: AsyncSession, dept_id: UUID) -> Department:
    res = await db.execute(select(Department).where(Department.id == dept_id))
    dept = res.scalar_one_or_none()
    if not dept:
        raise ValueError(f"Department {dept_id} not found")
    return dept


async def _department_risks(
    db: AsyncSession,
    dept_id: UUID,
    start_date: Optional[datetime],
    end_date: Optional[datetime],
) -> List[Risk]:
    conditions = [Risk.department_id == dept_id]
    if start_date:
        conditions.append(Risk.created_at >= start_date)
    if end_date:
        conditions.append(Risk.created_at <= end_date)

    stmt = (
        select(Risk)
        .where(and_(*conditions))
        .options(selectinload(Risk.owner), selectinload(Risk.department))
        .order_by(Risk.risk_score.desc())
    )
    res = await db.execute(stmt)
    return res.scalars().all()


async def _department_mitigations(
    db: AsyncSession,
    risk_ids: Sequence[UUID],
) -> List[MitigationAction]:
    if not risk_ids:
        return []

    stmt = (
        select(MitigationAction)
        .where(MitigationAction.risk_id.in_(list(risk_ids)))
        .options(selectinload(MitigationAction.assigned_to))
        .order_by(MitigationAction.due_date.asc())
    )
    res = await db.execute(stmt)
    return res.scalars().all()


def _pdf_watermark_and_pagenum(canvas, doc) -> None:  # reportlab callback
    from reportlab.lib import colors

    canvas.saveState()
    canvas.setFont("Helvetica-Bold", 48)
    canvas.setFillColor(colors.lightgrey)
    canvas.translate(300, 400)
    canvas.rotate(35)
    canvas.drawCentredString(0, 0, "CONFIDENTIAL")
    canvas.restoreState()

    canvas.saveState()
    canvas.setFont("Helvetica", 9)
    canvas.setFillColor(colors.grey)
    canvas.drawRightString(doc.pagesize[0] - 36, 20, f"Page {doc.page}")
    canvas.restoreState()


def _safe_filename(name: str) -> str:
    return "".join(c for c in name if c.isalnum() or c in ("-", "_", ".")).strip() or "report"


def _write_pdf_department_report(
    out_path: Path,
    department_name: str,
    period_label: str,
    generated_by: str,
    generated_at: datetime,
    risks: List[Risk],
    mitigations: List[MitigationAction],
) -> None:
    from reportlab.lib import colors
    from reportlab.lib.pagesizes import A4
    from reportlab.lib.styles import getSampleStyleSheet
    from reportlab.platypus import (
        PageBreak,
        Paragraph,
        SimpleDocTemplate,
        Spacer,
        Table,
        TableStyle,
    )

    styles = getSampleStyleSheet()
    doc = SimpleDocTemplate(str(out_path), pagesize=A4, title=f"Department Risk Report - {department_name}")

    story = []
    story.append(Paragraph(f"<b>Department Risk Report</b>", styles["Title"]))
    story.append(Spacer(1, 12))
    story.append(Paragraph(f"<b>Department:</b> {department_name}", styles["Normal"]))
    story.append(Paragraph(f"<b>Reporting period:</b> {period_label}", styles["Normal"]))
    story.append(Paragraph(f"<b>Generated by:</b> {generated_by}", styles["Normal"]))
    story.append(Paragraph(f"<b>Generated at:</b> {generated_at.strftime('%Y-%m-%d %H:%M UTC')}", styles["Normal"]))
    story.append(PageBreak())

    # Executive summary
    counts = {"Critical": 0, "High": 0, "Medium": 0, "Low": 0}
    for r in risks:
        counts[_band_label(float(r.risk_score or 1.0))] += 1

    story.append(Paragraph("<b>Executive Summary</b>", styles["Heading1"]))
    story.append(Paragraph(f"Total risks: <b>{len(risks)}</b>", styles["Normal"]))

    summary_data = [["Band", "Count"], *[[k, str(v)] for k, v in counts.items()]]
    summary_table = Table(summary_data, hAlign="LEFT")
    summary_table.setStyle(
        TableStyle(
            [
                ("BACKGROUND", (0, 0), (-1, 0), colors.black),
                ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
                ("GRID", (0, 0), (-1, -1), 0.5, colors.grey),
                ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
            ]
        )
    )
    story.append(Spacer(1, 10))
    story.append(summary_table)
    story.append(Spacer(1, 18))

    # Risk register table
    story.append(Paragraph("<b>Risk Register</b>", styles["Heading1"]))

    top5_ids = {r.id for r in risks[:5]}

    header = [
        "★",
        "Risk Title",
        "Category",
        "Owner",
        "Likelihood",
        "Impact",
        "Velocity",
        "Detectability",
        "Score",
        "Band",
        "Status",
    ]
    data = [header]
    for r in risks:
        raw = float(r.risk_score or 1.0)
        band = _band_label(raw)
        data.append(
            [
                "★" if r.id in top5_ids else "",
                r.title,
                str(r.category.value if hasattr(r.category, "value") else r.category),
                (r.owner.full_name if r.owner else ""),
                str(r.likelihood),
                str(r.impact),
                str(r.velocity),
                str(r.detectability),
                f"{normalise_score(raw):.1f}",
                band,
                str(r.status.value if hasattr(r.status, "value") else r.status),
            ]
        )

    table = Table(data, repeatRows=1)
    ts = TableStyle(
        [
            ("BACKGROUND", (0, 0), (-1, 0), colors.black),
            ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
            ("GRID", (0, 0), (-1, -1), 0.25, colors.grey),
            ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
            ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ]
    )

    # Colour-code each register row by band (full row)
    band_col = header.index("Band")
    star_col = 0
    num_cols = len(header)
    for i in range(1, len(data)):
        band = data[i][band_col]
        hex_colour = BAND_COLOURS.get(band)
        if not hex_colour:
            continue
        bg = colors.HexColor(hex_colour)
        row_text = colors.white if band in {"Critical", "High", "Low"} else colors.black
        for col in range(num_cols):
            ts.add("BACKGROUND", (col, i), (col, i), bg)
            ts.add("TEXTCOLOR", (col, i), (col, i), row_text)

    # Gold star marker in first column (top 5)
    for i in range(1, len(data)):
        if data[i][star_col] == "★":
            ts.add("TEXTCOLOR", (star_col, i), (star_col, i), colors.HexColor("#FFD54F"))
            ts.add("FONTNAME", (star_col, i), (star_col, i), "Helvetica-Bold")

    table.setStyle(ts)
    story.append(table)
    story.append(PageBreak())

    # Mitigation tracking table
    story.append(Paragraph("<b>Mitigation Tracking</b>", styles["Heading1"]))

    risk_title = {r.id: r.title for r in risks}
    mitig_header = ["Risk", "Mitigation", "Assigned To", "Due Date", "Status"]
    mitig_data = [mitig_header]

    now = datetime.now(timezone.utc)
    overdue_rows: List[int] = []
    for m in mitigations:
        status = str(m.status.value if hasattr(m.status, "value") else m.status)
        due = m.due_date.astimezone(timezone.utc) if m.due_date else None
        is_overdue = bool(due and due < now and m.status != MitigationStatus.COMPLETED)
        mitig_data.append(
            [
                risk_title.get(m.risk_id, str(m.risk_id)),
                m.description,
                (m.assigned_to.full_name if m.assigned_to else str(m.assigned_to_id)),
                due.strftime("%Y-%m-%d") if due else "",
                status,
            ]
        )
        if is_overdue:
            overdue_rows.append(len(mitig_data) - 1)

    mitig_table = Table(mitig_data, repeatRows=1)
    mts = TableStyle(
        [
            ("BACKGROUND", (0, 0), (-1, 0), colors.black),
            ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
            ("GRID", (0, 0), (-1, -1), 0.25, colors.grey),
            ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
        ]
    )
    for r in overdue_rows:
        mts.add("BACKGROUND", (0, r), (-1, r), colors.HexColor("#FFCDD2"))
        mts.add("TEXTCOLOR", (0, r), (-1, r), colors.HexColor("#B71C1C"))
        mts.add("FONTNAME", (0, r), (-1, r), "Helvetica-Bold")

    mitig_table.setStyle(mts)
    story.append(mitig_table)

    doc.build(story, onFirstPage=_pdf_watermark_and_pagenum, onLaterPages=_pdf_watermark_and_pagenum)


