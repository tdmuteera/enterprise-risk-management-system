async def generate_institutional_report(
    db: AsyncSession,
    out_path: Path,
    generated_by: str,
) -> ReportMeta:
    generated_at = datetime.now(timezone.utc)

    # IRI per dept (max IRI in dept)
    dep_res = await db.execute(select(Department).where(Department.is_active == True).order_by(Department.code))
    deps = dep_res.scalars().all()

    iri_pairs: List[Tuple[str, float]] = []
    for d in deps:
        iri_res = await db.execute(select(func.max(Risk.institutional_risk_index)).where(Risk.department_id == d.id))
        iri_val = float(iri_res.scalar() or 0.0)
        if iri_val <= 0:
            # Fallback so chart still conveys signal even if IRI recalculation has not run yet.
            score_res = await db.execute(select(func.max(Risk.risk_score)).where(Risk.department_id == d.id))
            raw_score = float(score_res.scalar() or 0.0)
            iri_val = float(normalise_score(raw_score)) if raw_score >= 1 else 0.0
        iri_pairs.append((d.code, iri_val))

    # Dept link matrix (counts)
    code_by_id = {d.id: d.code for d in deps}
    codes = [d.code for d in deps]
    idx = {c: i for i, c in enumerate(codes)}
    matrix = [[0 for _ in codes] for _ in codes]

    join_stmt = (
        select(
            RiskLink.source_risk_id,
            RiskLink.target_risk_id,
            Risk.department_id.label("src_dept"),
        )
        .select_from(RiskLink)
        .join(Risk, Risk.id == RiskLink.source_risk_id)
    )
    src_rows = (await db.execute(join_stmt)).all()

    tgt_join = (
        select(
            RiskLink.source_risk_id,
            RiskLink.target_risk_id,
            Risk.department_id.label("tgt_dept"),
        )
        .select_from(RiskLink)
        .join(Risk, Risk.id == RiskLink.target_risk_id)
    )
    tgt_rows = (await db.execute(tgt_join)).all()

    tgt_by_link = {(s, t): dept for s, t, dept in tgt_rows}

    for src_id, tgt_id, src_dept in src_rows:
        tgt_dept = tgt_by_link.get((src_id, tgt_id))
        if not src_dept or not tgt_dept:
            continue
        src_code = code_by_id.get(src_dept)
        tgt_code = code_by_id.get(tgt_dept)
        if not src_code or not tgt_code:
            continue
        i = idx[src_code]
        j = idx[tgt_code]
        matrix[i][j] += 1
        matrix[j][i] += 1

    # Risk chains
    risks_res = await db.execute(select(Risk.id, Risk.title, Risk.department_id).where(Risk.status != RiskStatus.CLOSED))
    risk_rows = risks_res.all()
    links_res = await db.execute(select(RiskLink.source_risk_id, RiskLink.target_risk_id, RiskLink.weight))
    link_rows = links_res.all()

    risks_dict = [{"id": str(rid), "title": title} for rid, title, _ in risk_rows]
    links_dict = [{"source_risk_id": str(s), "target_risk_id": str(t), "weight": float(w)} for s, t, w in link_rows]
    clusters = detect_risk_chain(risks_dict, links_dict)

    dept_by_risk = {str(rid): str(dept) for rid, _, dept in risk_rows}
    title_by_risk = {str(rid): title for rid, title, _ in risk_rows}

    narratives: List[str] = []
    for cluster in clusters:
        if len(cluster) < 3:
            continue
        depts_in = {dept_by_risk.get(rid) for rid in cluster}
        depts_in.discard(None)
        if len(depts_in) < 2:
            continue
        # narrative
        titles = [title_by_risk.get(rid, rid) for rid in cluster[:6]]
        narratives.append(
            "Cascading chain across departments: " + ", ".join(titles) + (" ..." if len(cluster) > 6 else "")
        )

    # Forensic summary (anonymised)
    f_stmt = (
        select(Alert.alert_type, func.count(Alert.id))
        .where(Alert.alert_type.in_([AlertType.FORENSIC_FLAG, AlertType.RISK_SUPPRESSION]))
        .group_by(Alert.alert_type)
    )
    f_res = await db.execute(f_stmt)
    forensic_summary = {
        str(t.value if hasattr(t, "value") else t): int(c) for t, c in f_res.all()
    }

    # Top 10 critical risks
    top_stmt = (
        select(Risk.title, Department.name, Risk.risk_score)
        .join(Department, Department.id == Risk.department_id)
        .where(Risk.risk_score >= 65 * 6.25)
        .order_by(Risk.risk_score.desc())
        .limit(10)
    )
    top_res = await db.execute(top_stmt)
    top_critical = [(t, d, normalise_score(float(s))) for t, d, s in top_res.all()]

    _write_pdf_institutional_report(
        out_path,
        generated_by=generated_by,
        generated_at=generated_at,
        department_iris=iri_pairs,
        dept_matrix=(codes, matrix),
        chain_narratives=narratives,
        forensic_summary=forensic_summary,
        top_critical=top_critical,
    )

    return ReportMeta(filename=_safe_filename("institutional-risk-report.pdf"), content_type="application/pdf")


