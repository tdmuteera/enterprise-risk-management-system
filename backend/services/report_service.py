async def generate_executive_report(db: AsyncSession, out_path: Path, generated_by: str) -> ReportMeta:
    generated_at = datetime.now(timezone.utc)

    # Scorecard from all risks (open only)
    r_stmt = select(Risk.risk_score).where(Risk.status != RiskStatus.CLOSED)
    r_res = await db.execute(r_stmt)
    scores = [float(x[0]) for x in r_res.all() if x[0] is not None]

    scorecard = {"Critical": 0, "High": 0, "Medium": 0, "Low": 0}
    for raw in scores:
        scorecard[_band_label(raw)] += 1

    # Top 5 institution-wide (exclude closed)
    top_stmt = (
        select(Risk.title, Department.name, Risk.risk_score)
        .join(Department, Department.id == Risk.department_id)
        .where(Risk.status != RiskStatus.CLOSED)
        .order_by(Risk.risk_score.desc())
        .limit(5)
    )
    top_res = await db.execute(top_stmt)
    top5 = [(t, d, normalise_score(float(s))) for t, d, s in top_res.all()]

    # Chains
    risks_res = await db.execute(select(Risk.id, Risk.title, Risk.department_id).where(Risk.status != RiskStatus.CLOSED))
    risk_rows = risks_res.all()
    links_res = await db.execute(select(RiskLink.source_risk_id, RiskLink.target_risk_id, RiskLink.weight))
    link_rows = links_res.all()
    risks_dict = [{"id": str(rid), "title": title} for rid, title, _ in risk_rows]
    links_dict = [{"source_risk_id": str(s), "target_risk_id": str(t), "weight": float(w)} for s, t, w in link_rows]
    clusters = detect_risk_chain(risks_dict, links_dict)
    title_by_risk = {str(rid): title for rid, title, _ in risk_rows}
    dept_by_risk = {str(rid): dept for rid, _, dept in risk_rows}

    narratives: List[str] = []
    for cluster in clusters:
        if len(cluster) < 3:
            continue
        depts_in = {dept_by_risk.get(rid) for rid in cluster}
        depts_in.discard(None)
        if len(depts_in) < 2:
            continue
        titles = [title_by_risk.get(rid, rid) for rid in cluster[:6]]
        narratives.append(
            "Cross-department chain: linked risks include "
            + "; ".join(titles)
            + (
                ". Further connected risks exist in the register."
                if len(cluster) > 6
                else " — escalation across units should be reviewed collectively."
            )
        )

    # IRI trend: sum of per-dept max IRI up to each day
    start = (generated_at - timedelta(days=29)).date()
    iri_trend: List[Tuple[str, float]] = []

    for i in range(30):
        day = start + timedelta(days=i)
        day_end = datetime(day.year, day.month, day.day, 23, 59, 59, tzinfo=timezone.utc)
        stmt = (
            select(Risk.department_id, func.max(Risk.institutional_risk_index))
            .where(Risk.updated_at <= day_end)
            .group_by(Risk.department_id)
        )
        res = await db.execute(stmt)
        vals = [float(v or 0.0) for _, v in res.all()]
        iri_trend.append((day.strftime("%m-%d"), round(sum(vals), 2)))

    _write_pdf_executive_report(out_path, generated_by, generated_at, scorecard, top5, narratives, iri_trend)

    return ReportMeta(filename=_safe_filename("executive-summary.pdf"), content_type="application/pdf")


def _write_excel_forensic_audit(
    out_path: Path,
    generated_by: str,
    generated_at: datetime,
    audit_rows: List[Tuple],
    alert_rows: List[Tuple],
    activity_rows: List[Tuple],
) -> None:
    from openpyxl import Workbook
    from openpyxl.styles import Alignment, Font, NamedStyle, PatternFill
    from openpyxl.utils import get_column_letter

    wb = Workbook()

    header = NamedStyle(name="header")
    header.font = Font(bold=True, color="FFFFFF")
    header.fill = PatternFill("solid", fgColor="000000")
    header.alignment = Alignment(horizontal="center", vertical="center")

    # Sheet 1: full audit trail (header row + data, freeze header)
    ws = wb.active
    ws.title = "AuditTrail"
    ws.merge_cells("A1:I1")
    ws["A1"] = "FORENSIC AUDIT REPORT (CONFIDENTIAL)"
    ws["A1"].font = Font(bold=True, size=14)
    ws.merge_cells("A2:I2")
    ws["A2"] = f"Generated by: {generated_by}  ·  {generated_at.strftime('%Y-%m-%d %H:%M UTC')}"

    cols = [
        "Changed At",
        "Risk ID",
        "Risk Title",
        "Action",
        "User",
        "IP",
        "User Agent",
        "Previous Values",
        "New Values",
    ]
    header_row = 3
    for c, name in enumerate(cols, start=1):
        cell = ws.cell(row=header_row, column=c, value=name)
        cell.style = header

    data_row = header_row + 1
    for changed_at, risk_id, risk_title, action, user_name, ip, ua, prev, new in audit_rows:
        action_s = action.value if hasattr(action, "value") else str(action)
        ws.cell(row=data_row, column=1, value=changed_at.isoformat() if changed_at else "")
        ws.cell(row=data_row, column=2, value=str(risk_id))
        ws.cell(row=data_row, column=3, value=risk_title)
        ws.cell(row=data_row, column=4, value=action_s)
        ws.cell(row=data_row, column=5, value=user_name)
        ws.cell(row=data_row, column=6, value=ip or "")
        ws.cell(row=data_row, column=7, value=ua or "")
        ws.cell(row=data_row, column=8, value=str(prev or {}))
        ws.cell(row=data_row, column=9, value=str(new or {}))
        data_row += 1

    ws.freeze_panes = ws["A4"]
    last_col_letter = get_column_letter(len(cols))
    ws.auto_filter.ref = f"A{header_row}:{last_col_letter}{header_row}"

    # Sheet 2: Forensic flags
    ws2 = wb.create_sheet("ForensicFlags")
    fcols = ["Created At", "Type", "Severity", "Message"]
    ws2.append(fcols)
    for c in range(1, len(fcols) + 1):
        ws2.cell(row=1, column=c).style = header

    for created_at, atype, severity, msg in alert_rows:
        ws2.append(
            [
                created_at.isoformat() if created_at else "",
                atype,
                severity,
                msg,
            ]
        )
    ws2.freeze_panes = "A2"
    ws2.auto_filter.ref = "A1:D1"

    # Sheet 3: User activity
    ws3 = wb.create_sheet("UserActivity")
    acols = ["User", "Action", "Count"]
    ws3.append(acols)
    for c in range(1, len(acols) + 1):
        ws3.cell(row=1, column=c).style = header

    for user_name, action, count in activity_rows:
        ws3.append([user_name, action, int(count)])

    ws3.freeze_panes = "A2"
    ws3.auto_filter.ref = "A1:C1"

    # Auto-fit column widths
    for sheet in [ws, ws2, ws3]:
        for idx, col in enumerate(sheet.columns, start=1):
            max_len = 0
            col_letter = get_column_letter(idx)
            for cell in col:
                try:
                    max_len = max(max_len, len(str(cell.value or "")))
                except Exception:
                    pass
            sheet.column_dimensions[col_letter].width = min(80, max(12, max_len + 2))

    wb.save(str(out_path))


async def generate_forensic_audit_report(
    db: AsyncSession,
    out_path: Path,
    generated_by: str,
    start_date: Optional[datetime],
    end_date: Optional[datetime],
) -> ReportMeta:
    from models.risk import RiskHistory

    generated_at = datetime.now(timezone.utc)
    start_date = _utc(start_date) or (generated_at - timedelta(days=30))
    end_date = _utc(end_date) or generated_at

    # Sheet 1: all RiskHistory in range with optional user + risk title.
    # Use LEFT JOINs so orphaned history rows are not dropped.
    stmt = (
        select(
            RiskHistory.changed_at,
            RiskHistory.risk_id,
            Risk.title,
            RiskHistory.action,
            User.full_name,
            RiskHistory.ip_address,
            RiskHistory.user_agent,
            RiskHistory.previous_values,
            RiskHistory.new_values,
        )
        .outerjoin(Risk, Risk.id == RiskHistory.risk_id)
        .outerjoin(User, User.id == RiskHistory.changed_by_id)
        .where(and_(RiskHistory.changed_at >= start_date, RiskHistory.changed_at <= end_date))
        .order_by(RiskHistory.changed_at.desc())
    )
    audit_rows = []
    for changed_at, risk_id, risk_title, action, user_name, ip_address, user_agent, previous_values, new_values in (
        await db.execute(stmt)
    ).all():
        audit_rows.append(
            (
                changed_at,
                risk_id,
                risk_title or "(risk deleted)",
                action,
                user_name or "System/Unknown",
                ip_address,
                user_agent,
                previous_values,
                new_values,
            )
        )

    # Sheet 2: forensic alerts in range
    a_stmt = (
        select(Alert.created_at, Alert.alert_type, Alert.severity, Alert.message)
        .where(
            and_(
                Alert.created_at >= start_date,
                Alert.created_at <= end_date,
                Alert.alert_type.in_([AlertType.FORENSIC_FLAG, AlertType.RISK_SUPPRESSION]),
            )
        )
        .order_by(Alert.created_at.desc())
    )
    alert_rows = [
        (
            ca,
            str(t.value if hasattr(t, "value") else t),
            str(s.value if hasattr(s, "value") else s),
            msg,
        )
        for ca, t, s, msg in (await db.execute(a_stmt)).all()
    ]

    # Sheet 3: user activity summary
    actor_name = func.coalesce(User.full_name, "System/Unknown")
    act_stmt = (
        select(actor_name, RiskHistory.action, func.count(RiskHistory.id))
        .outerjoin(User, User.id == RiskHistory.changed_by_id)
        .where(and_(RiskHistory.changed_at >= start_date, RiskHistory.changed_at <= end_date))
        .group_by(actor_name, RiskHistory.action)
        .order_by(func.count(RiskHistory.id).desc())
    )
    activity_rows = [
        (name, str(action.value if hasattr(action, "value") else action), cnt)
        for name, action, cnt in (await db.execute(act_stmt)).all()
    ]

    if not alert_rows:
        alert_rows = [(generated_at, "no_forensic_alerts", "info", "No forensic alerts found in selected date range.")]
    if not activity_rows:
        activity_rows = [("System", "no_activity", 0)]

    _write_excel_forensic_audit(out_path, generated_by, generated_at, audit_rows, alert_rows, activity_rows)

    return ReportMeta(
        filename=_safe_filename("forensic-audit.xlsx"),
        content_type="application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
    )
